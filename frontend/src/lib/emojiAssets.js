// onerror 换回原来的文字记号（见 highlight.js）。以后换一批图片，只要文件名和这里的
// 名字对得上就不用改代码。
//
// 没有列在这里的记号，例如 [表情]、[图片]、[分享视频]、[语音 3秒] 这类占位符，
// 或者 [小乔]、[米奇]、[喜羊羊] 这种别的表情包，在界面上继续按文字显示。

